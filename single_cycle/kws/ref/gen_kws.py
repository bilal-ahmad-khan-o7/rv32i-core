"""Generate everything the KWS programs and tests need from the .tflite model.

    python3 kws/ref/gen_kws.py

Writes, in kws/gen (all committed, like programs/dot64.*):
  kws_tables.h, kws_tables.c   weights, folded biases and requantisation tables
  layers.hex                   the layer table for tb_core_kws.sv and rv32iss
  input_<name>.hex             the input bytes, one file per input
  expect_<name>.hex            every layer's expected output for that input, then the label

Expected outputs come from TFLite's reference kernels, after checking that the
NumPy model gives the same bytes. Run check_ref.py for the full comparison.

Tables. For each output channel of each layer:
  bias' = bias - input_zp * sum(w)   the input zero point, folded in
  m2    = 2 * M as a uint32          see requant() and requant_once() in kws.c
  round = 2^(e-1), e = -shift        all shifts here are right shifts of at least 1
"""
import re

import numpy as np

import check_ref
import inputs
import model
import ref_numpy

ROOT = model.ROOT
GEN = ROOT / "kws" / "gen"
LINK = ROOT / "kws" / "sw" / "link.ld"

HEADER = """/* GENERATED by kws/ref/gen_kws.py from kws/model/kws_ref_model.tflite; do not edit.
 * Model: MLPerf Tiny keyword spotting (mlcommons/tiny), Apache-2.0. */
"""


def addresses():
    """The fixed addresses of link.ld."""
    return {m[0]: int(m[1], 16) for m in re.findall(r"^(\w+)\s*=\s*0x([0-9A-Fa-f]+);", LINK.read_text(), re.M)}


def fold_bias(bias, zp, weights):
    """weights: (channels, taps)."""
    return (bias.astype(np.int64) - zp * weights.astype(np.int64).sum(axis=1)).astype(np.int64)


def rq_rows(layer):
    rows = []
    for m, s in zip(layer.multiplier.tolist(), layer.shift.tolist()):
        assert (1 << 30) <= m < (1 << 31), "requant() in kws.c needs M in [2^30, 2^31)"
        assert s <= -1, "requant() in kws.c needs a right shift of at least 1"
        e = -s
        rows.append((2 * m, 1 << (e - 1), e))
    return rows


def braced(a):
    """A C initialiser for an array, with one pair of braces per dimension."""
    if a.ndim == 1:
        return ",".join(str(v) for v in a.tolist())
    return ",".join(f"{{{braced(r)}}}" for r in a)


def c_int8(name, a, dims):
    return f"const int8_t {name}{dims} __attribute__((aligned(4))) = {{{wrap(braced(a))}}};\n"


def c_int32(name, a, dims):
    return f"const int32_t {name}{dims} = {{{wrap(braced(a))}}};\n"


def c_rq(name, rows, dims):
    """rows: one rq_rows() list, or a list of them for a 2-D table."""
    def row(r):
        return ",".join(f"{{{m}u,{q},{e}}}" for m, q, e in r)
    body = row(rows) if isinstance(rows[0], tuple) else ",".join(f"{{{row(r)}}}" for r in rows)
    return f"const rq_t {name}{dims} = {{{wrap(body)}}};\n"


def wrap(s, width=110):
    out, line = [], ""
    for tok in s.split(","):
        if len(line) + len(tok) + 1 > width:
            out.append(line)
            line = ""
        line += tok + ","
    out.append(line)
    return "\n" + "\n".join(out) + "\n"


def write_tables(layers):
    dw = [l for l in layers.values() if l.kind == "depthwise"]
    pw = [l for l in layers.values() if l.kind == "conv" and l.id != 1]
    first, fc = layers[1], next(l for l in layers.values() if l.kind == "fc")
    assert len(dw) == 4 and len(pw) == 4

    h = HEADER + f"""#ifndef KWS_TABLES_H
#define KWS_TABLES_H

#include <stdint.h>

/* One output channel's requantisation: see requant() and requant_once() in kws.c. */
typedef struct {{ uint32_t m2; int32_t round; int32_t e; }} rq_t;

#define FC_OUTPUT_ZP {fc.output_zp}

extern const int8_t  conv0_w[64][40];
extern const int32_t conv0_b[64];
extern const rq_t    conv0_rq[64];
extern const int8_t  dw_w[4][64][9];
extern const int32_t dw_b[4][64];
extern const rq_t    dw_rq[4][64];
extern const int8_t  pw_w[4][64][64];
extern const int32_t pw_b[4][64];
extern const rq_t    pw_rq[4][64];
extern const int8_t  fc_w[12][64];
extern const int32_t fc_b[12];
extern const rq_t    fc_rq;

#endif
"""
    (GEN / "kws_tables.h").write_text(h, newline="\n")

    c = HEADER + '#include "kws_tables.h"\n\n'
    w = first.weights.reshape(64, 40)
    c += c_int8("conv0_w", w, "[64][40]")
    c += c_int32("conv0_b", fold_bias(first.bias, first.input_zp, w), "[64]")
    c += c_rq("conv0_rq", rq_rows(first), "[64]")

    # the file's depthwise layout is (1, 3, 3, 64): gather one channel's 9 taps
    dww = [l.weights.reshape(3, 3, 64).transpose(2, 0, 1).reshape(64, 9) for l in dw]
    c += c_int8("dw_w", np.stack(dww), "[4][64][9]")
    c += c_int32("dw_b", np.stack([fold_bias(l.bias, l.input_zp, w) for l, w in zip(dw, dww)]), "[4][64]")
    c += c_rq("dw_rq", [rq_rows(l) for l in dw], "[4][64]")

    pww = [l.weights.reshape(64, 64) for l in pw]
    c += c_int8("pw_w", np.stack(pww), "[4][64][64]")
    c += c_int32("pw_b", np.stack([fold_bias(l.bias, l.input_zp, w) for l, w in zip(pw, pww)]), "[4][64]")
    c += c_rq("pw_rq", [rq_rows(l) for l in pw], "[4][64]")

    c += c_int8("fc_w", fc.weights, "[12][64]")
    c += c_int32("fc_b", fold_bias(fc.bias, fc.input_zp, fc.weights), "[12]")
    (m, r, e), = {tuple(x) for x in rq_rows(fc)}          # one scale for the whole layer
    c += f"const rq_t fc_rq = {{{m}u, {r}, {e}}};\n"
    (GEN / "kws_tables.c").write_text(c, newline="\n")


def layer_rows(layers):
    """(marker, base, len, stride, count) for each checked layer, in order."""
    a = addresses()
    row = 7 * 64
    interior = a["buf_a"] + row + 64
    rows = []
    for l in layers.values():
        if l.kind == "conv":
            rows.append((l.id, interior, 5 * 64, row, 25))    # the result sits inside a 1-pixel border
        elif l.kind == "depthwise":
            rows.append((l.id, a["buf_b"], 8000, 8000, 1))
        elif l.kind == "pool":
            rows.append((l.id, a["pool_out"], 64, 64, 1))
        elif l.kind == "fc":
            rows.append((l.id, a["kws_output"], 12, 12, 1))
        elif l.kind == "softmax":
            rows.append((l.id, a["kws_label"], 4, 4, 1))      # not run: the arg-max label goes here
    return rows


def hex_words(data):
    """int8 array -> little-endian word hex, one word per line."""
    b = np.asarray(data, dtype=np.int8).tobytes()
    b += bytes(-len(b) % 4)
    return "".join(f"{w:08x}\n" for w in np.frombuffer(b, dtype="<u4").tolist())


def main():
    GEN.mkdir(exist_ok=True)
    it = model.open_interpreter()
    layers = model.load_layers(it)
    check_ref.check_fc_formula(layers[12])
    write_tables(layers)
    rows = layer_rows(layers)
    (GEN / "layers.hex").write_text("".join(f"{v:08x}\n" for r in rows for v in r), newline="\n")

    cases = inputs.regression()
    for name, x in cases.items():
        t = check_ref.tflite_layers(it, layers, x)
        n = ref_numpy.run(x, layers)
        expected = []
        for marker, *_ in rows:
            if layers[marker].kind == "softmax":
                expected.append(np.frombuffer(np.int32(np.argmax(t[12])).tobytes(), dtype=np.int8))
                continue
            if not np.array_equal(n[marker].ravel(), t[marker].ravel()):
                raise SystemExit(f"NumPy and TFLite differ on {name}, layer {marker}")
            expected.append(t[marker].ravel())
        (GEN / f"input_{name}.hex").write_text(hex_words(x), newline="\n")
        (GEN / f"expect_{name}.hex").write_text(hex_words(np.concatenate(expected)), newline="\n")
    print(f"wrote tables, {len(rows)} layer rows, {len(cases)} inputs to {GEN}")


if __name__ == "__main__":
    main()
